"""Per-level tables of Wolfenstein 3D (all six episodes in the id source; episodes 1 and 2 are the
20 levels of Zillion 3D): the ceiling colour of VGAClearScreen (vgaCeiling in WL_DRAW.C), the par
time of the intermission (parTimes in WL_INTER.C) and the music of a level (songs in WL_PLAY.C).

  python3 wl_levels.py          print the tables of the 20 levels
"""
import os, re, sys

import paths, sms, wl_names

NUM_EPISODES = 2
LEVELS_PER_EPISODE = 10
NUM_LEVELS = NUM_EPISODES * LEVELS_PER_EPISODE


def _first_block(text, marker):
    """Text between `marker` and the next `#else` (the non-SPEAR branch of the id source)."""
    i = text.index(marker)
    j = text.index("#else", i)
    return text[i:j]


def _src(name):
    return open(os.path.join(paths.SRC, "WOLFSRC", name), encoding="latin-1").read()


def tables():
    """-> (ceilings: VGA palette index per level, par: seconds per level, songs: MUS_* value per level)"""
    draw = _src("WL_DRAW.C")
    inter = _src("WL_INTER.C")
    play = _src("WL_PLAY.C")
    ceil_vals = [int(v, 16) & 0xFF for v in
                 re.findall(r"0x([0-9a-fA-F]{4})", _first_block(draw, "unsigned vgaCeiling[]"))]
    par_vals = [float(m.group(1)) for m in
                re.finditer(r'\{\s*([0-9.]+)\s*,\s*"[^"]+"\s*\}', _first_block(inter, "parTimes[]"))]
    song_names = re.findall(r"\b([A-Z0-9_]+_MUS)\b", _first_block(play, "int songs[]"))
    snd, mus = wl_names.audio_names()
    songval = dict(mus)
    songs = [songval[n] for n in song_names]
    n = NUM_LEVELS
    assert len(ceil_vals) >= n, len(ceil_vals)
    assert len(par_vals) >= n, len(par_vals)
    assert len(songs) >= n, len(songs)
    return ceil_vals[:n], [int(round(p * 60)) for p in par_vals[:n]], songs[:n]


def ceil_cram(d, ceil_index):
    """the ceiling colour of a level as an SMS CRAM byte (the view's palette entry 1 is per level)"""
    return sms.cram(sms.snap(d.pal8[ceil_index]))


def build(pk, H, C, d, cached):
    """the tables the game code needs: par time and music of every level (the ceiling colour goes to
    wl_maps.py, with the level data).  Banked code reads its constants from its own bank (the build's
    rule), so each table is a file of its own: lvl_par.c goes to the bank of inter.c, lvl_song.c to
    the bank of wl_play.c -- bank 0 has no room to spare (tools/checkrom.py)"""
    ceil_vals, par, songs = tables()
    gen = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'gen')
    with open(os.path.join(gen, 'lvl_par.c'), 'w') as f:
        f.write('/* generated by tools/wl_levels.py: parTimes[] of WL_INTER.C, seconds per level */\n')
        f.write('#include "game/def.h"\nconst u16 lvl_par[NUMMAPS] = {%s};\n' % ','.join(str(v) for v in par))
    with open(os.path.join(gen, 'lvl_song.c'), 'w') as f:
        f.write('/* generated by tools/wl_levels.py: songs[] of WL_PLAY.C */\n')
        f.write('#include "game/def.h"\nconst s16 lvl_song[NUMMAPS] = {%s};\n' % ','.join(str(v) for v in songs))
    H.append('extern const u16 lvl_par[NUMMAPS];    /* par time of the intermission, seconds (bank of inter.c) */')
    H.append('extern const s16 lvl_song[NUMMAPS];   /* music of a level (bank of wl_play.c) */')
    H.append('#define NUM_EPISODES %d' % NUM_EPISODES)
    H.append('#define LEVELS_PER_EPISODE %d' % LEVELS_PER_EPISODE)


if __name__ == '__main__':
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import wolfdata
    ceil_vals, par, songs = tables()
    d = wolfdata.Data(paths.DATA, paths.SRC)
    for i in range(NUM_LEVELS):
        print('E%d L%-2d ceil 0x%02X par %4ds song %2d' % (i // 10 + 1, i % 10 + 1, ceil_vals[i], par[i], songs[i]))
